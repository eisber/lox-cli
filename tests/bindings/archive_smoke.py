"""Installed-wheel/native archive regression tests and shared JVM fixtures."""

import argparse
import hashlib
import importlib.metadata
from pathlib import Path
import struct
import sys
import unittest
import zipfile

import lox_archive as archive


def prepare_fixtures(directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    raw = bytes.fromhex(Path(__file__).with_name("opaque.hex").read_text())
    encoded = archive.compress_loxcc(raw)
    if not isinstance(encoded, bytes):
        raise AssertionError(f"expected generated bytes, got {type(encoded)}")
    (directory / "raw.bin").write_bytes(raw)
    (directory / "encoded.bin").write_bytes(encoded)
    permissive = bytearray(encoded)
    permissive[4:16] = bytes(12)
    (directory / "permissive.bin").write_bytes(permissive)
    with zipfile.ZipFile(directory / "backup.zip", "w") as backup:
        backup.writestr("ignore.txt", b"unrelated")
        backup.writestr("nested/SPS0.LOXCC.suffix", encoded)
        backup.writestr("sps0.LoxCC", b"not the first match")
    with zipfile.ZipFile(directory / "empty.zip", "w"):
        pass
    with zipfile.ZipFile(directory / "badcrc.zip", "w") as backup:
        backup.writestr("sps0.LoxCC", encoded)
    corrupt = bytearray((directory / "badcrc.zip").read_bytes())
    central = corrupt.index(b"PK\x01\x02")
    crc = struct.unpack_from("<I", corrupt, central + 16)[0]
    struct.pack_into("<I", corrupt, central + 16, crc ^ 0xFFFFFFFF)
    (directory / "badcrc.zip").write_bytes(corrupt)
    (directory / "zero-offset.bin").write_bytes(encoded[:16] + b"\x00\x00\x00")
    (directory / "bad-offset.bin").write_bytes(encoded[:16] + b"\x00\x01\x00")


class ArchiveSmoke(unittest.TestCase):
    def test_native_bytes_roundtrip_and_selection(self):
        raw = (FIXTURES / "raw.bin").read_bytes()
        encoded = (FIXTURES / "encoded.bin").read_bytes()
        self.assertIsInstance(archive.compress_loxcc(raw), bytes)
        self.assertEqual(archive.compress_loxcc(raw), encoded)
        for result in (
            archive.decompress_loxcc(encoded),
            archive.extract_and_decompress(encoded),
            archive.extract_and_decompress((FIXTURES / "backup.zip").read_bytes()),
            archive.decompress_loxcc((FIXTURES / "permissive.bin").read_bytes()),
        ):
            self.assertIsInstance(result, bytes)
            self.assertEqual(result, raw)
        for data in (b"", bytes(range(256)) * 1024):
            self.assertEqual(archive.decompress_loxcc(archive.compress_loxcc(data)), data)
        print(f"Python bytes roundtrip: {len(raw)} bytes sha256={hashlib.sha256(raw).hexdigest()}")

    def test_native_typed_errors_and_source_context(self):
        cases = (
            (archive.decompress_loxcc, b"bad", archive.ArchiveError.HeaderTooShort, {"actual": 3}),
            (archive.decompress_loxcc, bytes(16), archive.ArchiveError.InvalidMagic, {"actual": 0}),
            (archive.decompress_loxcc, (FIXTURES / "zero-offset.bin").read_bytes(),
             archive.ArchiveError.ZeroBackReference, {"position": 1}),
            (archive.decompress_loxcc, (FIXTURES / "bad-offset.bin").read_bytes(),
             archive.ArchiveError.BackReferenceOutOfBounds, {"offset": 1, "output_len": 0}),
            (archive.extract_and_decompress, b"not a zip", archive.ArchiveError.InvalidZip, {}),
            (archive.extract_and_decompress, (FIXTURES / "empty.zip").read_bytes(),
             archive.ArchiveError.MissingConfigEntry, {}),
            (archive.extract_and_decompress, (FIXTURES / "badcrc.zip").read_bytes(),
             archive.ArchiveError.ReadZipEntry, {"index": 0, "name": "sps0.LoxCC"}),
        )
        for operation, data, error_type, fields in cases:
            with self.subTest(error_type=error_type):
                with self.assertRaises(error_type) as caught:
                    operation(data)
                error = caught.exception
                self.assertIsInstance(error, archive.ArchiveError)
                for name, value in fields.items():
                    self.assertEqual(getattr(error, name), value)
                if hasattr(error, "source_message"):
                    self.assertTrue(error.source_message)
                print(f"Python typed error: {error!r}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixtures", type=Path, required=True)
    args = parser.parse_args()
    FIXTURES = args.fixtures.resolve()
    # -I plus a fresh venv ensures this is the installed wheel, not source fallback.
    module_path = Path(archive.__file__).resolve()
    if not module_path.is_relative_to(Path(sys.prefix).resolve()):
        raise AssertionError(f"not installed in the active venv: {module_path}")
    print(f"Python installed package: {module_path}")
    print(f"Python distribution: {importlib.metadata.version('lox-archive')}")
    prepare_fixtures(FIXTURES)
    unittest.main(argv=[sys.argv[0]], verbosity=2)
